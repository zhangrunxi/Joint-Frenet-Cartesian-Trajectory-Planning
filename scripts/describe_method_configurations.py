"""Describe the configuration of every compared method.

The reviewer asks whether the compared planners were run with identical
bounds, geometry, safety margin, horizon and reference line, and whether the
baselines are official implementations. This script reads the configuration
that the runners actually pass to each planner, so that the table in the
response letter cannot drift away from the code.

Usage:
    python scripts/describe_method_configurations.py \\
        --output docs/method_configurations.md
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from run_paper_comparison import Settings  # noqa: E402

SHARED = [
    ("Vehicle geometry", "bus 6.50 m x 2.30 m, wheelbase 4.32 m, for every method"),
    ("Time step", "{dt} s"),
    ("Horizon", "{intervals} steps ({horizon} s)"),
    ("Road boundary margin", "{road_margin} m"),
    ("Obstacle margin", "{obstacle_margin} m"),
    ("Longitudinal acceleration", "{min_acc} to {max_acc} m/s^2"),
    ("Longitudinal jerk", "to {max_jerk} m/s^3"),
    ("Lateral acceleration", "to {max_lat_acc} m/s^2"),
    ("Lateral jerk", "to {max_lat_jerk} m/s^3"),
    ("Speed limit", "{max_speed} m/s"),
    ("Reference line", "circular road with the case curvature, for every method"),
    ("Obstacle prediction", "constant speed along the reference line, for every method"),
]

# method -> (states, obstacle model, collision constraint, solver backend)
METHODS = {
    "Xing joint corridor": (
        "7 (joint Cartesian-Frenet)",
        "corridor (Frenet safety corridor)",
        "corridor half-width, reference point",
        "OSQP, own implementation",
    ),
    "Xing joint corridor, point bounds": (
        "7 (joint Cartesian-Frenet)",
        "corridor (Frenet safety corridor)",
        "reference-point lateral offset",
        "OSQP, own implementation",
    ),
    "Xing joint, always yield": (
        "7 (joint Cartesian-Frenet)",
        "corridor (Frenet safety corridor)",
        "corridor half-width, reference point",
        "OSQP, own implementation",
    ),
    "Reiter direct elimination": (
        "5 (Frenet)",
        "ellipse or covering circles",
        "reference-point lateral offset",
        "SQP (CasADi/OSQP), re-implementation",
    ),
    "Reiter lifted ODE": (
        "8 (lifted Frenet)",
        "ellipse or covering circles",
        "reference-point lateral offset",
        "SQP (CasADi/OSQP), re-implementation",
    ),
    "This paper, six states": (
        "6 (Frenet)",
        "capsule plus four corner circles",
        "every capsule/circle pair",
        "SQP (acados/HPIPM), re-implementation",
    ),
    "This paper, nine states": (
        "9 (lifted Frenet)",
        "capsule plus four corner circles",
        "every capsule/circle pair",
        "SQP (acados/HPIPM), re-implementation",
    ),
    "This paper, AL-CiLQR": (
        "6 (Frenet)",
        "capsule plus four corner circles",
        "every capsule/circle pair",
        "AL-CiLQR (Python), re-implementation",
    ),
}

ABLATIONS = {
    "This paper, five covering circles": "the vehicle_gym fixed-radius covering, 5 circles",
    "This paper, paper N = 3": "the manuscript's Eq. 11-14 covering with N = 3",
    "This paper, paper N = 5": "the manuscript's Eq. 11-14 covering with N = 5",
    "This paper, frozen heading": "the proposed geometry with the heading deviation frozen",
    "This paper, pruned constraints": "only the critical circle pair is constrained",
    "This paper, capsule condition": "the Eq. 23 capsule-level sufficient condition",
    "This paper, kappa not a state": "the proposed geometry with kappa removed from the state",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    settings = Settings()
    horizon = settings.dt * settings.intervals

    lines = [
        "# Configuration of the compared methods",
        "",
        "This table is generated by `scripts/describe_method_configurations.py`,",
        "which reads the settings the runners actually pass to each planner.",
        "",
        "## Shared by every method",
        "",
        "| Item | Value |",
        "| --- | --- |",
    ]
    context = dict(vars(settings))
    context["horizon"] = horizon
    for label, value in SHARED:
        lines.append(f"| {label} | {value.format(**context)} |")

    lines += [
        "",
        "## Per method",
        "",
        "| Method | States | Obstacle model | Collision constraint | Solver |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name, values in METHODS.items():
        lines.append("| " + " | ".join((name,) + values) + " |")

    lines += [
        "",
        "## Ablations inside this paper's model",
        "",
        "All of these share the solver backend, the bounds, the horizon and the",
        "reference line with the six-state variant, and differ only in the",
        "quantity named.",
        "",
        "| Ablation | What is changed |",
        "| --- | --- |",
    ]
    for name, value in ABLATIONS.items():
        lines.append(f"| {name} | {value} |")

    lines += [
        "",
        "## Agreement with the parameters printed in the manuscript",
        "",
        "Table 1 of the manuscript lists the geometric and kinematic parameters of",
        "the test vehicle. The reconstruction uses the same values, so the bounds",
        "below are the bounds of the paper:",
        "",
        "| Manuscript Table 1 | Printed value | Value used here |",
        "| --- | ---: | ---: |",
        "| Total length | 6.50 m | 6.50 m |",
        "| Width | 2.30 m | 2.30 m |",
        "| Wheelbase | 4.32 m | 4.32 m |",
        f"| Max. acceleration | 2.50 m/s^2 | {settings.max_acc} m/s^2 |",
        f"| Max. deceleration | -3.00 m/s^2 | {settings.min_acc} m/s^2 |",
        "",
        "The curvature bounds are derived rather than set: the manuscript prints",
        "a curvature upper bound of 0.13 1/m and a curvature-rate upper bound of",
        "0.099 1/s, which follow from the maximum steering angle of 29.32 deg",
        "and the maximum steering rate of 24.55 deg/s over the 4.32 m wheelbase.",
        "",
        "## Cost weights",
        "",
        "The re-implementation of this paper uses the following stage weights,",
        "in the order of the cost function in the manuscript:",
        "",
        "    " + ", ".join(str(w) for w in settings.weights),
        "",
        "The Reiter re-implementation uses its own published weights",
        "(`qn = (10, 500, 1000, 1000, 10000)`), because the two formulations",
        "have different cost functions. The Xing reconstruction uses weights",
        "that the Xing publication does not disclose; the choice made here is",
        "recorded in `paper_comparison/model.py`.",
        "",
    ]

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines))
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
